BEGIN TRAN;

-- 1. povezivanje sa postojećim stanicama po nazivu
UPDATE ms SET StanicaID = x.ID
FROM #ms ms
CROSS APPLY (SELECT TOP 1 s.ID FROM planiranje.OP_Stanice s
             WHERE s.Naziv COLLATE Latin1_General_CI_AI = ms.Naziv COLLATE Latin1_General_CI_AI
             ORDER BY CASE WHEN s.IzvorniID IS NULL THEN 1 ELSE 0 END, s.ID) x;

-- 2. dopuna koordinata i ćiriličnog naziva
UPDATE s SET
    Latitude   = ISNULL(s.Latitude, ms.Lat),
    Longitude  = ISNULL(s.Longitude, ms.Lon),
    NazivCir   = ISNULL(s.NazivCir, NULLIF(ms.NazivCir, N'')),
    VrstaMesta = ISNULL(s.VrstaMesta, CASE ms.Vrsta WHEN N'halt' THEN N'stajalište' ELSE N'stanica' END)
FROM planiranje.OP_Stanice s JOIN #ms ms ON ms.StanicaID = s.ID;
PRINT N'Mreža: dopunjeno stanica ' + CAST(@@ROWCOUNT AS nvarchar(10));

-- 3. nova mesta iz mreže
INSERT planiranje.OP_Stanice (Naziv, NazivCir, VrstaMesta, Latitude, Longitude, Izvor, Kreirao)
SELECT ms.Naziv, NULLIF(ms.NazivCir, N''), CASE ms.Vrsta WHEN N'halt' THEN N'stajalište' ELSE N'stanica' END,
       ms.Lat, ms.Lon, N'MREZA', N'OP_003'
FROM #ms ms
WHERE ms.StanicaID IS NULL
  AND NOT EXISTS (SELECT 1 FROM planiranje.OP_Stanice s WHERE s.Izvor = N'MREZA' AND s.Naziv = ms.Naziv);
PRINT N'Mreža: novih mesta ' + CAST(@@ROWCOUNT AS nvarchar(10));

UPDATE ms SET StanicaID = s.ID
FROM #ms ms JOIN planiranje.OP_Stanice s ON s.Izvor = N'MREZA' AND s.Naziv = ms.Naziv
WHERE ms.StanicaID IS NULL;

-- 4. veze
INSERT planiranje.OP_MrezaVeza (StanicaAID, StanicaBID, DuzinaKm, Izvor)
SELECT DISTINCT a.StanicaID, b.StanicaID, e.km, N'MREZA'
FROM #me e
JOIN #ms a ON a.i = e.a
JOIN #ms b ON b.i = e.b
WHERE a.StanicaID <> b.StanicaID AND e.km > 0
  AND NOT EXISTS (SELECT 1 FROM planiranje.OP_MrezaVeza v
                  WHERE (v.StanicaAID = a.StanicaID AND v.StanicaBID = b.StanicaID)
                     OR (v.StanicaAID = b.StanicaID AND v.StanicaBID = a.StanicaID));
PRINT N'Mreža: novih veza ' + CAST(@@ROWCOUNT AS nvarchar(10));

COMMIT;
DROP TABLE #me;
DROP TABLE #ms;
